def zone_for_point(name: str) -> dict | None:
    zone = POINT_ZONES.get(name)
    if zone not in SEA_ZONES:
        return None
    forecast_reg, forecast_name, sea = SEA_ZONES[zone]
    return {
        "zone": zone,
        "forecast_reg": forecast_reg,
        "forecast_name": forecast_name,
        "sea": sea,
        "tide_system": 7 if sea == "서해" else 8,  # 서해안은 7물때식, 남해·동해·제주는 8물때식
        "warning_regions": [zone, *POINT_EXTRA_WARNINGS.get(name, [])],
    }
